import { mkdir, writeFile } from "node:fs/promises";
import { createTestDatabase } from "./lib/database.mjs";

// Reproducible types from the actual migrated PostgreSQL catalog, without Docker.
const db = await createTestDatabase();
try {
  const { rows: enums } = await db.query(`
    select t.typname as name, array_agg(e.enumlabel order by e.enumsortorder) as values
    from pg_type t join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public'
    group by t.typname order by t.typname
  `);
  const enumNames = new Set(enums.map((item) => item.name));
  const { rows: columns } = await db.query(`
    select table_name, column_name, udt_name, is_nullable, column_default
    from information_schema.columns where table_schema = 'public'
    order by table_name, ordinal_position
  `);
  const { rows: relationships } = await db.query(`
    select c.conname as name, r.relname as table_name, f.relname as referenced_relation,
      array(select a.attname from unnest(c.conkey) with ordinality k(num, ord)
        join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.num order by k.ord) as columns,
      array(select a.attname from unnest(c.confkey) with ordinality k(num, ord)
        join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.num order by k.ord) as referenced_columns
    from pg_constraint c join pg_class r on r.oid = c.conrelid
      join pg_class f on f.oid = c.confrelid
      join pg_namespace n on n.oid = r.relnamespace
      join pg_namespace fn on fn.oid = f.relnamespace
    where c.contype = 'f' and n.nspname = 'public' and fn.nspname = 'public'
    order by c.conname
  `);
  function columnType(type) {
    if (enumNames.has(type)) return `Database["public"]["Enums"]["${type}"]`;
    if (type.startsWith('_')) return `${columnType(type.slice(1))}[]`;
    if (['int2', 'int4', 'int8', 'numeric', 'float4', 'float8'].includes(type)) return 'number';
    if (type === 'bool') return 'boolean';
    if (['json', 'jsonb'].includes(type)) return 'Json';
    if (['text', 'uuid', 'timestamptz', 'varchar'].includes(type)) return 'string';
    throw new Error(`Unmapped PostgreSQL type: ${type}`);
  }
  const lines = [
    '// Generated by npm run db:types from supabase/migrations. Do not edit manually.',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    '', 'export type Database = {', '  public: {', '    Tables: {',
  ];
  for (const table of [...new Set(columns.map((column) => column.table_name))]) {
    lines.push(`      ${table}: {`);
    for (const mode of ['Row', 'Insert', 'Update']) {
      lines.push(`        ${mode}: {`);
      for (const column of columns.filter((column) => column.table_name === table)) {
        const nullable = column.is_nullable === 'YES';
        const optional = mode === 'Update' || (mode === 'Insert' && (nullable || column.column_default !== null));
        lines.push(`          ${column.column_name}${optional ? '?' : ''}: ${columnType(column.udt_name)}${nullable ? ' | null' : ''};`);
      }
      lines.push('        };');
    }
    const refs = relationships.filter((relation) => relation.table_name === table);
    lines.push('        Relationships: [');
    for (const ref of refs) {
      lines.push(`          { foreignKeyName: ${JSON.stringify(ref.name)}; columns: ${JSON.stringify(ref.columns)}; isOneToOne: false; referencedRelation: ${JSON.stringify(ref.referenced_relation)}; referencedColumns: ${JSON.stringify(ref.referenced_columns)}; },`);
    }
    lines.push('        ];', '      };');
  }
  lines.push('    };', '    Views: { [_ in never]: never };', '    Functions: {');
  const { rows: functions } = await db.query(`
    select p.proname as name, p.proargnames as names, p.pronargdefaults as defaults, r.typname as result,
      array(select t.typname from unnest(p.proargtypes) with ordinality a(oid, n)
        join pg_type t on t.oid = a.oid order by a.n) as types
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type r on r.oid = p.prorettype
    where n.nspname = 'public' and r.typname <> 'trigger' and not p.proretset
      and has_function_privilege('authenticated',p.oid,'execute') order by p.proname
  `);
  for (const fn of functions) {
    lines.push(`      ${fn.name}: { Args: {`);
    fn.types.forEach((type, index) => lines.push(`        ${fn.names[index]}${index >= fn.types.length - fn.defaults ? '?' : ''}: ${columnType(type)} | null;`));
    lines.push(`      }; Returns: ${columnType(fn.result)}; };`);
  }
  lines.push('    };', '    Enums: {');
  for (const item of enums) lines.push(`      ${item.name}: ${item.values.map((value) => JSON.stringify(value)).join(' | ')};`);
  lines.push('    };', '    CompositeTypes: { [_ in never]: never };', '  };', '};', '');
  await mkdir(new URL('../src/lib/database/', import.meta.url), { recursive: true });
  await writeFile(new URL('../src/lib/database/types.ts', import.meta.url), lines.join('\n'));
  console.log('Generated database types from migrated PostgreSQL schema.');
} finally {
  await db.close();
}
